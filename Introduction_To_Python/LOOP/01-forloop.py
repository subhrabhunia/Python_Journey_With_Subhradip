# SYNTAX OF FOR LOOP:
# for variable in sequence:
#     #Code to execute

# which we use for loop
# 1.list
# 2.tuple
# 3.String
# 4.dictionary
# 5.set
# 6.range of numbers


#Example
x=["HTML","CSS","JS","Python","MySQL"]
for subject in x:
    print(subject)

#List example
fruits=["Apple","Guava","Orange",'Banana']
for fruit in fruits:
    print(fruit)

#Tuple Example
Names=("Subhra","Soumya","Akash","Biswajit")
for name in Names:
    print(name)

#Set Example
Girls={"Riya","Sita","Mou","Mita"}
for girl in Girls:
    print(girl)

#String Example
subject="Python"
for letter in subject:
    print(letter)