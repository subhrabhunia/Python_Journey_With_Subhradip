# TYPES OF ARITHMETIC OPERATORS
# +------------------+-------------------------+-----------+
# | Operator         | Name                    | Example   |
# +------------------+-------------------------+-----------+
# | +                | Addition                | 10 + 5    |
# | -                | Subtraction             | 10 - 5    |
# | *                | Multiplication          | 10 * 5    |
# | /                | Division                | 10 / 5    |
# | %                | Modulus (Remainder)     | 10 % 5    |
# | //               | Floor Division          | 10 // 3   |
# | **               | Exponentiation (Power)  | 2 ** 3    |
# +------------------+-------------------------+-----------+
# Examples with Output:
# 10 + 5   = 15
# 10 - 5   = 5
# 10 * 5   = 50
# 10 / 5   = 2.0
# 10 % 5   = 0
# 10 // 3  = 3
# 2 ** 3   = 8   (2 × 2 × 2)