# TYPES:-
# 1. Implicit Type Casting

# Implicit Type Casting means Python automatically converts one data type into another.

# For example:

# a = 10        # int
# b = 5.5       # float

# result = a + b

# print(result)

# Here:

# int → float
# 10  → 10.0

# Then:

# 10.0 + 5.5 = 15.5

# Output:

# 15.5

# Python automatically converts the int into a float to avoid losing data.

# 2. Explicit Type Casting

# Explicit Type Casting means the programmer manually converts one data type into another.
